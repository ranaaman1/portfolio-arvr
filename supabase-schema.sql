create table if not exists public.portfolio_inquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(name) between 2 and 120),
  email text not null check (char_length(email) between 5 and 254),
  subject text not null check (char_length(subject) between 2 and 160),
  message text not null check (char_length(message) between 10 and 5000),
  source text
);

alter table public.portfolio_inquiries enable row level security;

revoke all on table public.portfolio_inquiries from anon, authenticated;
grant insert on table public.portfolio_inquiries to anon, authenticated;
grant usage on sequence public.portfolio_inquiries_id_seq to anon, authenticated;

drop policy if exists "Anyone can submit portfolio inquiries" on public.portfolio_inquiries;
create policy "Anyone can submit portfolio inquiries"
  on public.portfolio_inquiries
  for insert
  to anon, authenticated
  with check (true);
